export const LCD_COLUMNS = 16;

/** Whether the dot at (x, y) of character `char` is lit. Unknown characters print blank. */
export function lcdDot(char: string, x: number, y: number): boolean {
  if (y > 6) return false;
  const rows = GLYPHS[char] ?? GLYPHS[" "];
  return ((rows[y] >> (4 - x)) & 1) === 1;
}

export const lcdCharacters = Object.keys(GLYPHS);
